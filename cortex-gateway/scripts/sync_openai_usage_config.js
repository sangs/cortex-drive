#!/usr/bin/env node
'use strict';
/**
 * Writes the Python mirror of OpenAI usage config (FinOps release 1, 2026-11-16):
 *   src/mcp_server/config/openai_usage.json = config/openai_prices.json + the openai.* events of config/log_events.json
 *
 * The MCP, Bento and worker images contain only src/mcp_server/, so they cannot read the gateway's config. This file
 * is generated, never edited by hand; tests/verify_openai_usage.js fails if it is out of date.
 *
 *     node cortex-gateway/scripts/sync_openai_usage_config.js           # write
 *     node cortex-gateway/scripts/sync_openai_usage_config.js --check   # exit 1 if out of date
 */
const fs = require('fs');
const path = require('path');

const GATEWAY = path.join(__dirname, '..');
const MIRROR = path.join(GATEWAY, '..', 'src', 'mcp_server', 'config', 'openai_usage.json');
const EVENT_PREFIX = 'openai.';

function buildMirror() {
    const prices = JSON.parse(fs.readFileSync(path.join(GATEWAY, 'config', 'openai_prices.json'), 'utf8'));
    const logEvents = JSON.parse(fs.readFileSync(path.join(GATEWAY, 'config', 'log_events.json'), 'utf8'));
    const events = Object.fromEntries(Object.entries(logEvents.events).filter(([name]) => name.startsWith(EVENT_PREFIX)));
    const mirror = {
        _comment: 'GENERATED by cortex-gateway/scripts/sync_openai_usage_config.js from cortex-gateway/config/openai_prices.json '
            + 'and the openai.* events of cortex-gateway/config/log_events.json. Do not edit; edit those files and re-run the script.',
        max_string_chars: logEvents.max_string_chars,
        prices,
        events,
    };
    return `${JSON.stringify(mirror, null, 2)}\n`;
}

function main() {
    const expected = buildMirror();
    const current = fs.existsSync(MIRROR) ? fs.readFileSync(MIRROR, 'utf8') : null;
    if (process.argv.includes('--check')) {
        if (current !== expected) {
            console.error(`${path.relative(process.cwd(), MIRROR)} is out of date: run node cortex-gateway/scripts/sync_openai_usage_config.js`);
            process.exit(1);
        }
        return;
    }
    fs.mkdirSync(path.dirname(MIRROR), { recursive: true });
    fs.writeFileSync(MIRROR, expected);
    console.log(`wrote ${path.relative(process.cwd(), MIRROR)}`);
}

if (require.main === module) main();
module.exports = { buildMirror, MIRROR };
