'use strict';
/**
 * Builds routing_eval_set.json (cross-domain discovery design 2026-11-09 §4.1, evaluation gate):
 * hand_cases.js + templated cases over the real catalog titles, persons and topics. Templated labels:
 *   - a source title → its own domain (G3);
 *   - a person → the domains of their own work (catalog `work_domains`): one → single, several → cross;
 *   - a topic, broad wording → every domain with content on it (coverage_snapshot.json): none → discovery,
 *     one → single, several → cross (G5).
 * Run after regenerating the catalog or the coverage snapshot; commit the output.
 *     node tests/routing_eval/build_eval_set.js
 */
const fs = require('fs');
const path = require('path');

const HERE = __dirname;
const catalog = require('../../config/entity_catalog.json');
const coverage = require('./coverage_snapshot.json').coverage;
const { topics } = require('./topics.json');
const hand = require('./hand_cases.js');

const TEMPLATES = {
    career: ['Tell me about {t}.', 'What is recorded about {t}?'],
    podcast: ['What was discussed in {t}?', 'Who appeared on {t}?'],
    document: ['What are the main findings of {t}?', 'What does {t} say about its method?'],
};
const TOPIC_TEMPLATES = ['Tell me about {t}', 'Find discussion about {t}'];
const PERSON_TEMPLATE = 'What has {t} worked on?';

const cases = [];
const seen = new Set();
const add = (q, domains, mode, rule, note, origin) => {
    if (seen.has(q.toLowerCase())) return;
    seen.add(q.toLowerCase());
    cases.push({ id: `R${String(cases.length + 1).padStart(3, '0')}`, q, domains: [...domains].sort(), mode, rule, note: note || '', origin });
};

for (const [q, domains, mode, rule, note] of hand) add(q, domains, mode, rule, note, 'hand');

const topicNames = new Set(topics.map(t => t.toLowerCase()));
for (const e of catalog.entries) {
    if (e.domain === 'person') {
        const work = (e.work_domains || []).slice().sort();
        // A person sharing a first name with another person is still named in full here.
        if (work.length) add(PERSON_TEMPLATE.replace('{t}', e.name), work, work.length > 1 ? 'cross' : 'single', 'G4', 'templated person', 'person');
        continue;
    }
    // Titles that are also topics ("Apache Iceberg", "Graph database") are topics first (design §4.1 rule 1): hand cases only.
    if (topicNames.has(e.name.toLowerCase())) continue;
    for (const tpl of TEMPLATES[e.domain] || []) add(tpl.replace('{t}', e.name), [e.domain], 'single', 'G3', 'templated title', 'title');
}

for (const t of topics) {
    const domains = coverage[t.toLowerCase()] || [];
    const mode = domains.length === 0 ? 'discovery' : domains.length === 1 ? 'single' : 'cross';
    for (const tpl of TOPIC_TEMPLATES) add(tpl.replace('{t}', t), domains, mode, 'G5', 'templated topic', 'topic');
}

const out = {
    _comment: 'Generated by build_eval_set.js from hand_cases.js, the entity catalog and coverage_snapshot.json. Do not edit by hand.',
    generated_at: new Date().toISOString(),
    catalog_generated_at: catalog.generated_at,
    count: cases.length,
    cases,
};
fs.writeFileSync(path.join(HERE, 'routing_eval_set.json'), JSON.stringify(out, null, 1));
const by = cases.reduce((m, c) => (m[c.origin] = (m[c.origin] || 0) + 1, m), {});
const modes = cases.reduce((m, c) => (m[c.mode] = (m[c.mode] || 0) + 1, m), {});
console.log(`routing_eval_set.json: ${cases.length} cases`, by, modes);
